/* =========================================================
   QUESTION BANK VALIDATION
   ========================================================= */

function buildQuestionBank(){

    const target = {
        APTITUDE: 30,
        COMPUTER: 20,
        REASONING: 25,
        CODING: 25
    };

    for (const section of Object.keys(target)) {

        const count = QUESTION_BANK.filter(
            q => q.section === section
        ).length;

        if (count !== target[section]) {

            throw new Error(
                `${section} must contain ${target[section]} questions, but contains ${count}.`
            );

        }
    }

    if (QUESTION_BANK.length !== 100) {

        throw new Error(
            `Question bank must contain exactly 100 questions. Found ${QUESTION_BANK.length}.`
        );

    }

    return QUESTION_BANK;
}
